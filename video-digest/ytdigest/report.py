"""report: one text-model pass (or map-reduce for long transcripts) that turns
a VideoBundle into the Report JSON vbench defined.

The transcript text and the video link are attached by the renderer, never
generated by the model.
"""

from __future__ import annotations

from .transcript import plain_text

FIELDS = (
    "one_line, about, text_summary, visual_summary, key_points[], life_applications[], "
    "action_items[], tags[], video_type, is_artistic, language, chapters[{t,title}], "
    "notable_quotes[{t,quote}], related_suggestions[], confidence"
)

SYSTEM = (
    "You write a report about a YouTube video so its reader can skip watching it and still "
    "get everything useful. You only state what the transcript and frame descriptions support. "
    "Answer with one JSON object only."
)


def _lang_name(lang: str) -> str:
    return {"pl": "Polish", "en": "English"}.get(lang, "Polish")


def _timeline(segments: list[dict], every: float = 30.0) -> str:
    """Transcript with a [mm:ss] marker roughly every 30 s, so the model can cite times."""
    out, next_mark = [], 0.0
    for s in segments:
        if s["start"] >= next_mark:
            m, sec = divmod(int(s["start"]), 60)
            out.append(f"\n[{m:02d}:{sec:02d}] ")
            next_mark = s["start"] + every
        out.append(s["text"] + " ")
    return "".join(out).strip()


def _frames_text(frames: list[dict]) -> str:
    rows = []
    for f in frames:
        if not (f.get("caption") or f.get("ocr_text")):
            continue
        m, s = divmod(int(f["t"]), 60)
        line = f"[{m:02d}:{s:02d}] {f.get('caption') or ''}"
        if f.get("ocr_text"):
            line += f" | on screen: {f['ocr_text'][:300]}"
        rows.append(line)
    return "\n".join(rows) or "(no visual analysis)"


def _meta(bundle: dict) -> str:
    ch = "; ".join(f"{int(c['t'])}s {c['title']}" for c in bundle.get("yt_chapters") or [])
    return (
        f"title: {bundle['title']}\nchannel: {bundle['channel']}\nduration_sec: {bundle['duration_sec']}\n"
        f"published_at: {bundle.get('published_at')}\nyoutube tags: {bundle.get('yt_tags', [])[:20]}\n"
        f"chapters: {ch}\ndescription: {(bundle.get('description') or '')[:1500]}"
    )


def _instructions(lang: str, video_type: str) -> str:
    return f"""Write every text field in {_lang_name(lang)}. The video type is {video_type}.
Return JSON with: {FIELDS}.
- one_line: one sentence, what the viewer gets from this video.
- about: 2-4 sentences, what the video is about and for whom.
- text_summary: what was said, 1-3 short paragraphs, specific (numbers, names, claims, arguments).
- visual_summary: what the picture showed that the speech did not (slides, code, charts, places, demos). Say plainly if the visuals add nothing.
- key_points: 4-10 concrete takeaways.
- life_applications: 2-5 ways the reader can use this in their own life or work.
- action_items: 0-5 concrete next steps worth doing, or [] if none.
- tags: 4-10 lowercase topic tags in {_lang_name(lang)}.
- chapters: [{{"t": seconds, "title": "..."}}]; reuse YouTube chapters if given, else make 3-8 from the [mm:ss] marks.
- notable_quotes: up to 4 short verbatim quotes with their time in seconds.
- related_suggestions: 2-5 related topics, books, people or searches to explore next.
- confidence: 0.0-1.0, how complete your source material was."""


def _map(client, ref: str, text: str, lang: str, n: int, total: int) -> str:
    user = (
        f"Part {n} of {total} of a video transcript. Write dense notes in {_lang_name(lang)}: every claim, "
        f"number, name, recommendation and story, keeping the [mm:ss] marks. No intro.\n\n{text}"
    )
    return client.complete(ref, "You take precise notes from transcripts.", user, max_tokens=2500)


def build(client, ref: str, bundle: dict, cfg: dict, video_type: str) -> dict:
    lang = cfg["report_language"]
    segments = bundle["transcript"]["segments"]
    body = _timeline(segments)
    if len(body) > cfg["max_transcript_chars"]:
        size = cfg["chunk_chars"]
        parts = [body[i : i + size] for i in range(0, len(body), size)]
        notes = [_map(client, ref, p, lang, n, len(parts)) for n, p in enumerate(parts, 1)]
        source_label, source_text = "Notes from the transcript, part by part", "\n\n".join(notes)
    else:
        source_label, source_text = "Transcript", body or "(no transcript available)"
    user = (
        f"{_meta(bundle)}\n\n{source_label}:\n{source_text}\n\n"
        f"Key frames (what was on screen):\n{_frames_text(bundle.get('frames', []))}\n\n"
        f"{_instructions(lang, video_type)}"
    )
    rep = client.json(ref, SYSTEM, user, max_tokens=5000)
    return normalise(rep, video_type, bundle, lang)


def normalise(rep: dict, video_type: str, bundle: dict, lang: str) -> dict:
    lists = ("key_points", "life_applications", "action_items", "tags", "related_suggestions")
    for k in lists:
        v = rep.get(k) or []
        rep[k] = [str(x).strip() for x in v if str(x).strip()] if isinstance(v, list) else [str(v)]
    rep["tags"] = sorted({t.lower().lstrip("#").replace(",", " ")[:90] for t in rep["tags"]})
    for k in ("one_line", "about", "text_summary", "visual_summary"):
        rep[k] = str(rep.get(k) or "").strip()
    rep["chapters"] = [c for c in rep.get("chapters") or [] if isinstance(c, dict) and "t" in c]
    if bundle.get("yt_chapters"):
        rep["chapters"] = bundle["yt_chapters"]
    rep["notable_quotes"] = [q for q in rep.get("notable_quotes") or [] if isinstance(q, dict) and q.get("quote")]
    rep["video_type"] = video_type
    rep["is_artistic"] = False
    rep["language"] = lang
    try:
        rep["confidence"] = float(rep.get("confidence") or 0.5)
    except (TypeError, ValueError):
        rep["confidence"] = 0.5
    if not bundle["transcript"]["segments"]:
        rep["confidence"] = min(rep["confidence"], 0.3)
    return rep


def artistic_stub(bundle: dict, reason: str) -> dict:
    """Report for music/artistic videos: listed, not analysed."""
    return {
        "one_line": "", "about": reason, "text_summary": "", "visual_summary": "", "key_points": [],
        "life_applications": [], "action_items": [], "tags": [], "video_type": "music_artistic",
        "is_artistic": True, "language": bundle.get("language"), "chapters": bundle.get("yt_chapters") or [],
        "notable_quotes": [], "related_suggestions": [], "confidence": 1.0,
    }


def transcript_text(bundle: dict) -> str:
    return plain_text(bundle["transcript"]["segments"])
